K_STABLE_MAX = 10000    # k < 10000 : 안정
K_CAUTION_MAX = 15000   # 10000 <= k < 15000 : 주의, k >= 15000 : 위험

LABELS = ["안정", "주의", "위험"]


def label_from_k(k):
    """k 값 → 3단계 라벨 인덱스 (0=안정, 1=주의, 2=위험)."""
    if k < K_STABLE_MAX:
        return 0
    elif k < K_CAUTION_MAX:
        return 1
    else:
        return 2


